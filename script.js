// 📝 Условия задачи «Камень, ножницы, бумага»Ввод пользователя: Программа просит 
// пользователя ввести одно из трёх слов: камень, ножницы или бумага.Ход компьютера: 
// Компьютер случайным образом выбирает свой вариант (число от 1 до 3, которое превращается в слово).
// Логика игры:Если выборы совпали — это ничья.Камень побеждает ножницы, но проигрывает бумаге.
// Ножницы побеждают бумагу, но проигрывают камню.Бумага побеждает камень, но проигрывает ножницам.
// Вывод: Программа должна показать, что выбрал компьютер, и объявить результат игры («Вы победили!», 
//   «Вы проиграли!» или «Ничья!»).


function randomNum(min, max) {
  let randomNum = Math.floor(Math.random()*(max-min+1)+min);
  return randomNum;
}
let userChoice = prompt("Введите камень, ножницы или бумага").toLowerCase();//toLowerCase() преобразует введённый текст в нижний регистр(маленькие буквы)
let computerChoice = randomNum(1, 3);
switch (computerChoice) {
  case 1:
    computerChoice = "камень";
    break;
  case 2:
    computerChoice = "ножницы";
    break;
  case 3:
    computerChoice = "бумага";
    break;
}
if (userChoice === computerChoice) {
  alert(`Компьютер выбрал ${computerChoice}. Ничья!`);
} else if ((userChoice === "камень" && computerChoice === "ножницы") || 
           (userChoice === "ножницы" && computerChoice === "бумага") || 
           (userChoice === "бумага" && computerChoice === "камень")) {
  alert(`Компьютер выбрал ${computerChoice}. Вы победили!`);
} else {
  alert(`Компьютер выбрал ${computerChoice}. Вы проиграли!`);
}
